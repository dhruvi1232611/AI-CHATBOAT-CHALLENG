"""Export the analysis as a proposal-ready Markdown draft."""


def to_markdown(an: dict, est: dict, mermaid_arch: str, settings: dict) -> str:
    n = an["narrative"]
    L = ["# Technical Proposal Draft", "", "## Executive summary", n["executive_summary"], "",
         "## Requirements", "| ID | Type | Category | Priority | Requirement |", "|---|---|---|---|---|"]
    L += [f"| {r['id']} | {r['type']} | {r['category']} | {r['priority']} | {r['text']} |" for r in an["requirements"]]
    L += ["", "## Clarifying questions"] + [f"- {m['question']}" for m in an["missing"]] + [f"- {q}" for q in n["additional_questions"]]
    L += ["", "## Proposed architecture", f"**Stack:** {an['stack']['selected']['name']}", "", n["architecture_rationale"], "",
          "```mermaid", mermaid_arch, "```", "", "## Effort & timeline",
          f"- Total: **{est['total_hours']} hours** (range {est['low']}-{est['high']})",
          f"- Duration: ~{est['weeks']} weeks ({est['sprints']} sprints, team of {settings['team_size']})",
          f"- Indicative cost: INR {est['cost']:,}", f"- Confidence: {est['confidence']}", "",
          "| Phase | Hours |", "|---|---|"] + [f"| {p['Phase']} | {p['Hours']} |" for p in est["phases"]]
    L += ["", "## Risks", "| Risk | Severity | Mitigation |", "|---|---|---|"]
    L += [f"| {r['risk']} | {r['severity']} | {r['mitigation']} |" for r in n["risks"]]
    L += ["", "## Assumptions"] + [f"- {a}" for a in n["assumptions"]]
    L += ["", "_Draft generated by the Cynbit Scoping Copilot. Requires senior architect review before sharing with the client._"]
    return "\n".join(L)
